// ── resolve ──────────────────────────────────────────────────────────────

export interface ResolveArgs {
  ts: bigint;
  fixtureSummary: ScoresBatchSummary;
  fixtureProof: ProofNode[];
  mainTreeProof: ProofNode[];
  statA: StatTerm;
  statB?: StatTerm | null;
}

export interface ResolveAccounts {
  market: PublicKey;
  epochDay: number; // needed to derive daily_scores_merkle_roots
  caller: PublicKey;
}

/** Caller supplies ONLY proof material (Dayo M4a P0 #1 structural fix,
 * enforced on-chain in resolve()'s body): predicate/stat_a_key/stat_b_key/op
 * are read from market state, never passed here. daily_scores_merkle_roots
 * is derived cross-program under TXORACLE_PROGRAM_ID from epochDay. */
export function buildResolve(
  args: ResolveArgs,
  accounts: ResolveAccounts
): BuiltInstruction {
  const [dailyScoresMerkleRoots] = dailyScoresRootsPda(accounts.epochDay);

  const w = new Writer();
  w.raw(Buffer.from(IX_DISCRIMINATOR.resolve));
  w.i64(args.ts);
  writeScoresBatchSummary(w, args.fixtureSummary);
  writeVec(w, args.fixtureProof, writeProofNode);
  writeVec(w, args.mainTreeProof, writeProofNode);
  writeStatTerm(w, args.statA);
  writeOption(w, args.statB, writeStatTerm);

  return {
    programId: PARI_MARKET_PROGRAM_ID,
    keys: [
      { pubkey: accounts.market, isSigner: false, isWritable: true },
      { pubkey: dailyScoresMerkleRoots, isSigner: false, isWritable: false },
      { pubkey: TXORACLE_PROGRAM_ID, isSigner: false, isWritable: false },
      { pubkey: accounts.caller, isSigner: true, isWritable: false },
    ],
    data: w.toBuffer(),
  };
}

